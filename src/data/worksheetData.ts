/**
 * Intelligent semantic grading function for short answers
 */
export function evaluateIsianAnswer(
  questionId: number, 
  rawInput: string
): { score: number; feedback: string; status: 'correct' | 'partial' | 'review_needed' | 'incorrect' } {
  const normalized = (rawInput || '').trim().toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()]/g, ' ');

  if (!normalized || normalized.length < 2) {
    return {
      score: 0,
      feedback: 'Jawaban belum diisi.',
      status: 'incorrect'
    };
  }

  if (questionId === 11) {
    const isAbuBakar = normalized.includes('abu') && normalized.includes('bakar');
    if (isAbuBakar) {
      return { score: 10, feedback: 'Tepat sekali! Sahabat setia tersebut adalah Abu Bakar Ash-Shiddiq r.a.', status: 'correct' };
    }
    return { score: 0, feedback: 'Kurang tepat. Sahabat yang menemani perjalanan hijrah adalah Abu Bakar Ash-Shiddiq r.a.', status: 'incorrect' };
  }

  if (questionId === 12) {
    const isTsur = normalized.includes('tsur') || normalized.includes('tsawr') || normalized.includes('sur');
    if (isTsur) {
      return { score: 10, feedback: 'Tepat sekali! Gua tempat bersembunyi adalah Gua Tsur.', status: 'correct' };
    }
    return { score: 0, feedback: 'Kurang tepat. Gua tempat bersembunyi selama tiga hari adalah Gua Tsur.', status: 'incorrect' };
  }

  if (questionId === 13) {
    const isMuhajirin = normalized.includes('muhajir') || normalized.includes('muhajirin');
    if (isMuhajirin) {
      return { score: 10, feedback: 'Benar sekali! Mereka disebut Kaum Muhajirin.', status: 'correct' };
    }
    return { score: 0, feedback: 'Kurang tepat. Kaum Muslimin yang berpindah dari Makkah disebut Kaum Muhajirin.', status: 'incorrect' };
  }

  // Soal 14: HOTS Tindakan Kaum Ansar
  if (questionId === 14) {
    const positiveTokens = ['ajak', 'kenal', 'bantu', 'tolong', 'tunjuk', 'sapa', 'bagi', 'main', 'teman', 'ramah', 'senyum', 'antar', 'pinjam'];
    const matches = positiveTokens.filter(token => normalized.includes(token));

    if (matches.length >= 1 && normalized.split(' ').length >= 2) {
      return {
        score: 10,
        feedback: 'Hebat! Tindakanmu sangat mulia dan mencerminkan semangat persaudaraan kaum Ansar.',
        status: 'correct'
      };
    } else if (normalized.length > 5) {
      return {
        score: 8,
        feedback: 'Bagus! Jawabanmu menunjukkan niat baik. Perlu diperiksa guru untuk apresiasi lengkap.',
        status: 'review_needed'
      };
    } else {
      return {
        score: 4,
        feedback: 'Jawaban terlalu singkat. Jelaskan tindakan nyata seperti mengajak berkenalan atau membantu.',
        status: 'partial'
      };
    }
  }

  // Soal 15: HOTS Dua Tindakan Usaha & Tawakal
  if (questionId === 15) {
    const effortTokens = ['jadwal', 'rencana', 'bagi', 'coba', 'belajar', 'tanya', 'guru', 'orang tua', 'bantu', 'ulang', 'usaha'];
    const tawakalTokens = ['doa', 'berdoa', 'allah', 'pasrah', 'mohon', 'sholat', 'ibadah', 'tenang'];

    const hasEffort = effortTokens.some(t => normalized.includes(t));
    const hasTawakal = tawakalTokens.some(t => normalized.includes(t));
    const wordCount = normalized.split(/\s+/).filter(Boolean).length;

    if (hasEffort && hasTawakal) {
      return {
        score: 10,
        feedback: 'Sempurna! Kamu telah mencakup unsur ikhtiar (usaha nyata) dan tawakal (berdoa memohon pertolongan Allah).',
        status: 'correct'
      };
    } else if ((hasEffort || hasTawakal) && wordCount >= 4) {
      return {
        score: 8,
        feedback: 'Bagus sekali! Kamu sudah menuliskan tindakan yang relevan. Perlu diperiksa guru untuk penilaian penuh.',
        status: 'review_needed'
      };
    } else if (wordCount >= 3) {
      return {
        score: 5,
        feedback: 'Jawaban cukup baik, namun pastikan menyebutkan dua tindakan nyata (ikhtiar dan doa).',
        status: 'partial'
      };
    } else {
      return {
        score: 2,
        feedback: 'Jawaban terlalu singkat. Tuliskan dua langkah nyata saat menghadapi kesulitan belajar.',
        status: 'partial'
      };
    }
  }

  return { score: 5, feedback: 'Jawaban dicatat untuk ditinjau guru.', status: 'review_needed' };
}
